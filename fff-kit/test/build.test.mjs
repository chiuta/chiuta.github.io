// Teste build.mjs: apply / idempotență / remove / check / info. Rulare: node test/build.test.mjs
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync, spawnSync, execSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {tmpDir, FIXTURE, check, summary, launch, newPage} from './_pw.mjs';
import {recomputeCspHashes, checkCspHashes} from '../lib/csp.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BUILD = path.join(HERE, '..', 'build.mjs');
const run = (args, opt = {}) => spawnSync('node', [opt.build || BUILD, ...args], {encoding: 'utf8'});
const sha = (s) => createHash('sha256').update(s).digest('hex');
const mk = (html, name = 'index.html') => { const d = tmpDir(); fs.writeFileSync(path.join(d, name), html); return d; };
const rf = (d) => fs.readFileSync(path.join(d, 'index.html'), 'utf8');
const ORIG = recomputeCspHashes(FIXTURE).html; // fixture cu hash-uri CSP corecte

console.log('apply');
const d = mk(ORIG);
check('fixture inițial: CSP valid', checkCspHashes(ORIG).ok);
let r = run(['apply', d, '--slug', 'demo-fff', '--modules', 'core,label,bundle']);
check('apply: cod 0', r.status === 0, r.stderr + r.stdout);
const h1 = rf(d);
check('bloc între marcaje, imediat după <meta charset>', /<meta charset="utf-8">\n<!--fff:kit:start v=1 modules=core,label,bundle-->/.test(h1) && h1.includes('<!--fff:kit:end-->'));
check('bloc: meta fff-app, style, script, i18n JSON', h1.includes('<meta name="fff-app" content="demo-fff">') && h1.includes('<style id="fff-style">') && h1.includes('<script id="fff-kit">') && h1.includes('<script type="application/json" id="fff-i18n">'));
check('kitul e înaintea scriptului aplicației', h1.indexOf('id="fff-kit"') < h1.indexOf("var c = parseInt"));
check('modulele în ordinea core, label, bundle', h1.indexOf('---- fff-kit/core') < h1.indexOf('---- fff-kit/label') && h1.indexOf('---- fff-kit/label') < h1.indexOf('---- fff-kit/bundle'));
check('CSP: hash-uri valide, fără unsafe-inline la scripturi', checkCspHashes(h1).ok && !/script-src[^;]*unsafe-inline/.test(h1));
check('check: ok', run(['check', d]).status === 0);
r = run(['apply', d, '--slug', 'demo-fff', '--modules', 'core,label,bundle']);
check('apply idempotent (octet cu octet)', rf(d) === h1);
check('un singur bloc după reaplicare', (rf(d).match(/fff:kit:start/g) || []).length === 1);
run(['apply', d, '--modules', 'core']);
const hc = rf(d);
check('apply cu alt set de module înlocuiește blocul (fără slug nou: îl păstrează)', (hc.match(/fff:kit:start/g) || []).length === 1 && hc.includes('modules=core-->') && !hc.includes('fff-kit/label') && hc.includes('content="demo-fff"') && checkCspHashes(hc).ok);
run(['apply', d, '--slug', 'demo-fff', '--modules', 'label,bundle,core']);
check('ordinea modulelor din linia de comandă nu contează', rf(d) === h1);

console.log('erori clare');
r = run(['apply', d, '--slug', 'x', '--modules', 'label']);
check('fără core → eroare', r.status !== 0 && /core/.test(r.stderr), r.stderr);
r = run(['apply', d, '--slug', 'x', '--modules', 'core,nu-exista']);
check('modul necunoscut → eroare', r.status !== 0 && /necunoscut/.test(r.stderr), r.stderr);
r = run(['apply', mk(ORIG), '--modules', 'core,label']);
check('slug lipsă (fără meta fff-app) → eroare', r.status !== 0 && /slug/.test(r.stderr), r.stderr);
const kitCopy = tmpDir('kit-');
fs.mkdirSync(path.join(kitCopy, 'src')); fs.mkdirSync(path.join(kitCopy, 'i18n')); fs.mkdirSync(path.join(kitCopy, 'lib'));
for (const f of ['build.mjs']) fs.copyFileSync(path.join(HERE, '..', f), path.join(kitCopy, f));
fs.copyFileSync(path.join(HERE, '..', 'lib/csp.mjs'), path.join(kitCopy, 'lib/csp.mjs'));
for (const f of ['core.js', 'label.js', 'bundle.js', 'kit.css']) fs.copyFileSync(path.join(HERE, '..', 'src', f), path.join(kitCopy, 'src', f));
for (const f of ['label.json', 'bundle.json']) fs.copyFileSync(path.join(HERE, '..', 'i18n', f), path.join(kitCopy, 'i18n', f));
const dm = mk(ORIG);
r = run(['apply', dm, '--slug', 'x', '--modules', 'core,qr,srs'], {build: path.join(kitCopy, 'build.mjs')});
check('modul opțional lipsă (src/qr.js) → eroare clară, fișierul neatins', r.status !== 0 && /module lipsă/.test(r.stderr) && /qr/.test(r.stderr) && rf(dm) === ORIG, r.stderr);
fs.writeFileSync(path.join(kitCopy, 'src/qr.js'), '(function(){window.FFF.qr={ping:1};})();');
r = run(['apply', dm, '--slug', 'x', '--modules', 'core,qr'], {build: path.join(kitCopy, 'build.mjs')});
check('modul opțional prezent (fără i18n) → se concatenează + avertisment', r.status === 0 && rf(dm).includes('FFF.qr={ping:1}') && /lipsește i18n\/qr.json/.test(r.stderr), r.stderr);
fs.writeFileSync(path.join(kitCopy, 'src/qr.js'), 'var s = "</script>";');
r = run(['apply', dm, '--slug', 'x', '--modules', 'core,qr'], {build: path.join(kitCopy, 'build.mjs')});
check('sursă cu „</script” refuzată', r.status !== 0 && /script/.test(r.stderr));

console.log('remove');
const dr = mk(ORIG);
run(['apply', dr, '--slug', 'demo-fff', '--modules', 'core,label,bundle']); run(['info', dr]);
r = run(['remove', dr]);
check('remove: revine exact la fișierul original', r.status === 0 && rf(dr) === ORIG);
check('remove: check eșuează (nu mai e kit)', run(['check', dr]).status !== 0);
check('remove repetat: nimic de scos, nu strică', run(['remove', dr]).status === 0 && rf(dr) === ORIG);

console.log('CSP: variante');
const noStyleCsp = ORIG.replace("style-src 'unsafe-inline'", "style-src 'self'");
const dn = mk(noStyleCsp); run(['apply', dn, '--slug', 'demo-fff']);
const hn = rf(dn);
check('style-src fără unsafe-inline → hash pentru stilul kitului', /style-src 'self' 'sha256-[A-Za-z0-9+/=]+'/.test(hn) && run(['check', dn]).status === 0);
run(['apply', dn, '--slug', 'demo-fff']);
check('reaplicare: nu se acumulează hash-uri de stil', rf(dn) === hn && (rf(dn).match(/style-src[^;]*/)[0].match(/sha256/g) || []).length === 1);
run(['remove', dn]);
check('remove: scoate hash-ul de stil', rf(dn) === noStyleCsp, rf(dn).match(/style-src[^;]*/)?.[0]);
const noCsp = ORIG.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n/, '');
const d0 = mk(noCsp); run(['apply', d0, '--slug', 'demo-fff']);
check('fără CSP: apply/check ok, remove restaurează', run(['check', d0]).status === 0 && (run(['remove', d0]), rf(d0) === noCsp));
const noCharset = ORIG.replace('<meta charset="utf-8">\n', '');
const dc = mk(noCharset); run(['apply', dc, '--slug', 'demo-fff']);
check('fără <meta charset>: blocul intră după <head>', /<head>\n<!--fff:kit:start/.test(rf(dc)) && run(['check', dc]).status === 0 && (run(['remove', dc]), rf(dc) === noCharset));
const onlyStyleCsp = ORIG.replace(/; style-src 'unsafe-inline'/, '');
const ds = mk(onlyStyleCsp); run(['apply', ds, '--slug', 'demo-fff']);
check('default-src \'none\' fără style-src → se adaugă style-src cu hash; remove îl scoate', /style-src 'sha256-/.test(rf(ds)) && (run(['remove', ds]), rf(ds) === onlyStyleCsp), rf(ds).match(/Content-Security[^>]*/)?.[0]);
const unsafeCsp = ORIG.replace(/script-src '[^;]*;/, "script-src 'unsafe-inline';");
const du = mk(unsafeCsp); run(['apply', du, '--slug', 'demo-fff']);
check('script-src cu unsafe-inline: CSP-ul scripturilor neatins', /script-src 'unsafe-inline';/.test(rf(du)) && run(['check', du]).status === 0);
const crlf = mk(ORIG.replace(/\n/g, '\r\n'));
r = run(['apply', crlf, '--slug', 'demo-fff']);
check('fișier CRLF: apply reușește (cu avertisment la hash-uri)', r.status === 0 && /CRLF/.test(r.stderr), r.stderr);
const badUtf = tmpDir(); fs.writeFileSync(path.join(badUtf, 'index.html'), Buffer.concat([Buffer.from(ORIG), Buffer.from([0xff, 0xfe, 0x41])]));
r = run(['apply', badUtf, '--slug', 'x']);
check('fișier non-UTF-8 refuzat, nemodificat', r.status !== 0 && /UTF-8/.test(r.stderr));

console.log('check');
const dk = mk(ORIG); run(['apply', dk, '--slug', 'demo-fff']);
fs.writeFileSync(path.join(dk, 'index.html'), rf(dk).replace('var c = parseInt', 'var cc = parseInt'));
r = run(['check', dk]);
check('script modificat → hash CSP invalid detectat (cod 1)', r.status === 1 && /hash-uri CSP/.test(r.stdout), r.stdout);
const dk2 = mk(ORIG); run(['apply', dk2, '--slug', 'demo-fff']);
fs.writeFileSync(path.join(dk2, 'index.html'), rf(dk2).replace('<!--fff:kit:end-->', ''));
check('marcaj lipsă detectat', run(['check', dk2]).status === 1);
const dk3 = mk(ORIG.replace('<span id="app-version">v 1.2.3 · 2026-10-14</span>', '').replace('<meta name="application-version" content="1.2.3">\n', ''));
run(['apply', dk3, '--slug', 'demo-fff']);
r = run(['check', dk3]);
check('lipsă #app-version / meta versiune → eroare; cu --lax → avertisment', r.status === 1 && /app-version/.test(r.stdout) && run(['check', dk3, '--lax']).status === 0);
check('check --json', JSON.parse(run(['check', dk, '--json']).stdout).ok === false);

console.log('info');
const di = mk(ORIG.replace("window.__fx = {fetchTry: function(){ return fetch('https://example.org/x'); }};", [
  "window.__fx = {a: function(){ return fetch('https://api.example.org/x'); }};",
  "var ws = new WebSocket('wss://sock.example.net/s'); navigator.geolocation.getCurrentPosition(function(){}); navigator.mediaDevices.getUserMedia({audio:true}); new Worker('w.js'); speechSynthesis.speak(1); navigator.clipboard.writeText('x'); indexedDB.open('x'); crypto.subtle.digest('SHA-256', new Uint8Array(1));",
  "localStorage.getItem('app.theme'); localStorage.setItem(\"app.scores\", 1); sessionStorage.getItem('sess.only'); localStorage.removeItem('app.old');",
].join('\n')).replace('</head>', '<link rel="stylesheet" href="https://fonts.example.com/css"><link rel="canonical" href="https://canon.example.com/"><link rel="manifest" href="manifest.json"><script src="https://cdn.example.io/lib.js"></script></head>').replace('</main>', '<a href="https://linkonly.example.com/">link</a><img src="https://img.example.org/a.png" alt=""><svg xmlns="http://www.w3.org/2000/svg"></svg></main>').replace("connect-src 'none'", "connect-src https://csp.example.com 'self'"));
run(['apply', di, '--slug', 'demo-fff']);
fs.writeFileSync(path.join(di, 'fff.config.json'), JSON.stringify({egressNote: 'Doar la acțiunea utilizatorului.', description: 'Descriere din config', selfModifying: true, sha256: 'nu-se-suprascrie'}));
r = run(['info', di]);
check('info: cod 0', r.status === 0, r.stderr);
const info = JSON.parse(fs.readFileSync(path.join(di, 'app.json'), 'utf8'));
const hosts = info.egress.map((e) => e.host);
check('egress: fetch, WebSocket, link stylesheet, script src, img src, CSP connect-src', ['api.example.org', 'sock.example.net', 'fonts.example.com', 'cdn.example.io', 'img.example.org', 'csp.example.com'].every((h) => hosts.includes(h)), hosts);
check('egress: NU include <a href>, link canonical, namespace SVG, nici kitul', !hosts.some((h) => /linkonly|canon|w3\.org/.test(h)), hosts);
check('egress: via indică sursa', info.egress.find((e) => e.host === 'api.example.org').via.includes('fetch') && info.egress.find((e) => e.host === 'csp.example.com').via.includes('csp:connect-src'));
const perms = info.permissions;
check('permisiuni detectate', ['getUserMedia', 'geolocation', 'Worker', 'speechSynthesis', 'clipboard', 'indexedDB', 'Web Crypto', 'localStorage'].every((p) => perms.includes(p)), perms);
check('permisiuni: fără false-positive din kit (serviceWorker, WebGL, Notification)', !perms.some((p) => ['serviceWorker', 'WebGL', 'WebGPU', 'Notification', 'RTCPeerConnection', 'BroadcastChannel'].includes(p)), perms);
check('storageKeys literale (fără sessionStorage, fără fff.*)', info.storageKeys.join() === 'app.old,app.scores,app.theme,fx.count,fx.note,lang', info.storageKeys);
check('nume, versiune, dată, descriere din meta; config suprascrie/adaugă', info.name === 'Demo FFF' && info.version === '1.2.3' && info.updated === '2026-10-14' && info.description === 'Descriere din config' && info.egressNote === 'Doar la acțiunea utilizatorului.' && info.selfModifying === true);
check('config nu poate suprascrie sha256/sizeBytes', /^[0-9a-f]{64}$/.test(info.sha256));
check('features: export/import/i18n/pwa/module', info.features.export && info.features.import && info.features.i18n.join() === 'ro,en,fr' && info.features.pwa.manifest === true && info.features.modules.join() === 'core,label,bundle');
check('kit: versiune + module; csp rezumat', info.kit.version === '1.0.0' && info.kit.modules.length === 3 && info.csp.present && info.csp.scriptInline === 'hash' && info.csp.directives['script-src'] === 'sha256×2', info.csp);
const html = rf(di);
const size = Buffer.byteLength(html);
check('sizeBytes = dimensiunea fișierului', info.sizeBytes === size, [info.sizeBytes, size]);
const canon = html.replace(/data-fff-hash="[0-9a-f]*"/g, 'data-fff-hash=""').replace(/"sha256":"[0-9a-f]*"/g, '"sha256":""');
check('sha256 = SHA-256 al fișierului canonic (calculat independent)', sha(canon) === info.sha256 && html.includes(`<html lang="ro" data-fff-hash="${info.sha256}">`));
const emb = JSON.parse(html.match(/<script type="application\/json" id="fff-info">([\s\S]*?)<\/script>/)[1]);
check('fff-info încorporat = app.json', JSON.stringify(emb) === JSON.stringify(info));
const viaShell = execSync(`LC_ALL=C sed -E 's/data-fff-hash="[0-9a-f]*"/data-fff-hash=""/g; s/"sha256":"[0-9a-f]*"/"sha256":""/g' ${JSON.stringify(path.join(di, 'index.html'))} | sha256sum`, {shell: '/bin/bash', encoding: 'utf8'}).split(' ')[0];
check('același hash cu comanda sed|sha256sum', viaShell === info.sha256);
check('info e urmat de check ok', run(['check', di]).status === 0);
const before = rf(di); run(['info', di]);
check('info idempotent (fișier și app.json identice)', rf(di) === before);
run(['apply', di, '--slug', 'demo-fff']);
check('apply după info: hash-ul rămâne valid și identic', run(['check', di]).status === 0 && rf(di) === before);
run(['apply', di, '--slug', 'demo-fff', '--modules', 'core']);
const info2 = JSON.parse(fs.readFileSync(path.join(di, 'app.json'), 'utf8'));
check('apply cu alt set de module reîmprospătează info (module, hash)', info2.kit.modules.join() === 'core' && run(['check', di]).status === 0 && info2.sha256 !== info.sha256);
fs.writeFileSync(path.join(di, 'index.html'), rf(di).replace('<p>', '<p> '));
r = run(['check', di]);
check('fișier modificat după info → „SHA-256 … învechit”', r.status === 1 && /învechit/.test(r.stdout), r.stdout);
run(['remove', di]);
check('remove scoate și blocul fff-info și atributul data-fff-hash', !/fff-info|data-fff-hash|fff:kit/.test(rf(di)));
const dz = mk(ORIG);
r = run(['info', dz, '--slug', 'solo']);
check('info fără kit: funcționează (kit:null) și check nu cere kit pentru hash', r.status === 0 && JSON.parse(fs.readFileSync(path.join(dz, 'app.json'), 'utf8')).kit === null);
const dp = mk(ORIG); run(['apply', dp, '--slug', 'demo-fff']);
r = run(['info', dp, '--probe']);
const ip = JSON.parse(fs.readFileSync(path.join(dp, 'app.json'), 'utf8'));
check('info --probe (Playwright): pornește pagina cu rețea blocată și adaugă date runtime', r.status === 0 && Array.isArray(ip.storageKeys), r.stderr);

console.log('--disable');
const dd = mk(ORIG); run(['apply', dd, '--slug', 'demo-fff', '--disable', 'se salvează singură']);
check('--disable scrie <meta name="fff-disable">', rf(dd).includes('<meta name="fff-disable" content="se salvează singură">'));
fs.writeFileSync(path.join(dd, 'fff.config.json'), JSON.stringify({disable: 'din config'}));
run(['apply', dd, '--slug', 'demo-fff']);
check('disable din fff.config.json', rf(dd).includes('content="din config"'));

console.log('integrare: pagina rezultată rulează curat');
const b = await launch(); const p = await newPage(b);
await p.page.goto('file://' + path.join(d, 'index.html')); await p.page.waitForTimeout(300);
await b.close();
check('0 erori CSP/pagină', p.errors.length === 0, p.errors);
summary('build');
